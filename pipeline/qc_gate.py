#!/usr/bin/env python3
"""qc_gate.py - the pre-card gate of the daily pipeline. Nothing reaches the owner's card unless this says PASS.

    python3 pipeline/qc_gate.py --channel oa --video final.mp4 --cover cover.jpg --timeline timeline.json \
        --voice-meta voice/narration.voice.json --rights rights.json --meta meta.json --captions captions.srt --report qc.json

Checks (FAIL blocks the card, WARN is reported on it):
  video      /yt-qc --profile long: streams, 1920x1080 30 fps, duration, black frames, freezes, loudness, decode, segments
  cover      frame 0 equals the cover (PSNR >= 30 dB at 1280x720); motion starts right after it (frame 0 vs 0.5 s differ)
  text       no burned subtitles: the timeline has no caption track drawn into the picture; the SRT is uploaded separately
  atlas      placement issues reported by the renderer (projection over face/caption/edge) = 0; ATLAS share <= 30 %
  voice      the narration is the channel's final voice (OA Adam, NEXORA Matilda) and the file matches its metadata
  rights     every asset in the timeline has url + licence + credit; no forbidden source; licences in the allowed list
  thumbnail  /yt-package thumbcheck (objective half of the cover gate)
  metadata   title 1-100 chars, description with sources and credits, captions file valid
"""
import argparse, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
import engine as E  # noqa: E402

ALLOWED_LICENCES = re.compile(r"public domain|\bPD\b|CC0|CC BY(-SA)? [0-9.]+|CC BY(-SA)?\b|NASA media guidelines|USGS|NOAA|Copernicus|"
                              r"original|own work|channel-made|generated by the pipeline", re.I)
FORBIDDEN = re.compile(r"spacex|esri|maxar|airbus|planet labs|google earth|3d tiles|getty|shutterstock|reuters|ap photo", re.I)


def run(cmd, timeout=1800):
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def frame(video, t, path):
    run(["ffmpeg", "-v", "error", "-y", "-ss", str(t), "-i", video, "-frames:v", "1", "-vf", "scale=1280:720", path])
    return os.path.isfile(path)


def psnr(a, b):
    p = run(["ffmpeg", "-v", "info", "-i", a, "-i", b, "-lavfi", "[0:v]scale=1280:720,format=rgb24[x];[1:v]scale=1280:720,format=rgb24[y];[x][y]psnr", "-f", "null", "-"])
    m = re.search(r"average:([0-9.]+|inf)", p.stderr)
    return float("inf") if m and m.group(1) == "inf" else (float(m.group(1)) if m else 0.0)


def check(name, ok, detail, level="FAIL"):
    return {"check": name, "result": "PASS" if ok else level, "detail": detail}


def gate(a, cfg):
    res, work = [], a.work or os.path.join(os.path.dirname(os.path.abspath(a.report)), ".qc")
    os.makedirs(work, exist_ok=True)
    ch = cfg["channels"][a.channel]
    # 1. video file through the existing QC
    qc = run([sys.executable, os.path.join(ROOT, ".claude", "skills", "yt-qc", "qc.py"), a.video, "--profile", "long"] +
             (["--manifest", a.manifest] if a.manifest else []))
    try:
        q = json.loads(qc.stdout)
    except ValueError:
        q = {"result": "FAIL", "error": qc.stdout[-300:] + qc.stderr[-300:]}
    res.append(check("video (yt-qc long)", q.get("result") == "PASS", {k: q.get(k) for k in ("result", "failures", "warnings", "error") if k in q}))
    # 2. first frame = cover, then motion
    f0, f1 = os.path.join(work, "f0.png"), os.path.join(work, "f05.png")
    if frame(a.video, 0, f0) and frame(a.video, 0.5, f1):
        p0, p01 = psnr(f0, a.cover), psnr(f0, f1)
        res.append(check("first frame = cover", p0 >= 30, {"psnr_db": round(p0, 1), "need": ">= 30"}))
        res.append(check("motion right after the cover", p01 < 45, {"psnr_frame0_vs_0.5s_db": round(p01, 1), "need": "< 45 (frames differ)"}))
    else:
        res.append(check("first frame = cover", False, "could not extract frames"))
    # 3. text: no burned subtitles
    tl = json.load(open(a.timeline)) if a.timeline else {}
    burned = bool(tl.get("captions")) or bool((tl.get("subtitles") or {}).get("burn_in", False))
    res.append(check("no burned subtitles", not burned, "timeline captions/subtitles drawn into the picture" if burned else "SRT only (uploaded as a track)"))
    # 4. atlas placement
    if a.manifest and os.path.isfile(a.manifest):
        man = json.load(open(a.manifest))
        at = man.get("atlas") or {}
        issues = at.get("placement_issues") or at.get("issues") or []
        n_issues = len(issues) if isinstance(issues, list) else int(issues or 0)
        res.append(check("atlas placement", n_issues == 0, {"issues": n_issues}))
        share = at.get("screen_share")
        if share is not None:
            res.append(check("atlas share <= 30 %", share <= 0.30, {"share": share}, "WARN"))
    # 5. voice
    if a.voice_meta:
        md = json.load(open(a.voice_meta))
        ok = md.get("voice_id") == ch["voice"]["voice_id"] and md.get("provider") == "elevenlabs"
        res.append(check("final voice", ok, {"voice_id": md.get("voice_id"), "want": ch["voice"]["voice_id"], "name": ch["voice"]["name"]}))
        wav = os.path.join(os.path.dirname(a.voice_meta), md.get("audio", "narration.wav"))
        if os.path.isfile(wav):
            res.append(check("voice file matches metadata", E.sha_file(wav) == md.get("audio_sha256"), md.get("audio_sha256", "")[:12]))
    else:
        res.append(check("final voice", False, "no voice metadata"))
    # 6. rights
    rights = json.load(open(a.rights)) if a.rights else {"assets": []}
    by_src = {r["src"]: r for r in rights.get("assets", [])}
    srcs = [v.get("src") for v in (tl.get("assets") or {}).values() if isinstance(v, dict) and v.get("src")]
    srcs += [c.get("src") for c in tl.get("clips", []) if c.get("src")]
    missing, bad = [], []
    for s in srcs:
        r = by_src.get(s)
        if not r or not all(r.get(k) for k in ("url", "licence", "credit")):
            missing.append(s)
        elif FORBIDDEN.search(r["url"] + " " + r["credit"] + " " + r["licence"]) or not ALLOWED_LICENCES.search(r["licence"]):
            bad.append({"src": s, "licence": r["licence"], "credit": r["credit"]})
    res.append(check("rights ledger", not missing and not bad, {"assets": len(srcs), "missing": missing, "not_allowed": bad}))
    # 7. thumbnail
    tc = run([sys.executable, os.path.join(ROOT, ".claude", "skills", "yt-package", "thumbcheck.py"), a.cover])
    try:
        t = json.loads(tc.stdout)
        t = t[0] if isinstance(t, list) else t
        res.append(check("thumbnail gate (objective)", t.get("result") == "PASS", {k: t.get(k) for k in ("result", "failed", "metrics") if k in t}, "WARN"))
    except ValueError:
        res.append(check("thumbnail gate (objective)", False, tc.stdout[-200:], "WARN"))
    # 8. metadata
    meta = json.load(open(a.meta))
    title, desc = meta.get("title", ""), meta.get("description", "")
    res.append(check("title", 1 <= len(title) <= 100 and not re.search(r"[<>]", title), {"chars": len(title)}))
    res.append(check("description sources + credits", "http" in desc and len(desc.encode()) <= 5000 and not re.search(r"[<>]", desc),
                     {"bytes": len(desc.encode())}))
    srt = open(a.captions, encoding="utf-8").read() if a.captions else ""
    res.append(check("captions SRT", bool(re.search(r"^\d+\s*\n\d\d:\d\d:\d\d,\d{3} --> ", srt, re.M)), {"cues": srt.count(" --> ")}))
    fails = [r["check"] for r in res if r["result"] == "FAIL"]
    out = {"result": "PASS" if not fails else "FAIL", "failures": fails, "warnings": [r["check"] for r in res if r["result"] == "WARN"],
           "checks": res, "video_sha256": E.sha_file(a.video), "cover_sha256": E.sha_file(a.cover)}
    with open(a.report, "w") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for k in ("channel", "video", "cover", "meta", "report"):
        ap.add_argument("--" + k, required=True)
    for k in ("timeline", "manifest", "voice-meta", "rights", "captions", "work"):
        ap.add_argument("--" + k)
    a = ap.parse_args(argv)
    out = gate(a, E.load_config())
    print(json.dumps({k: out[k] for k in ("result", "failures", "warnings")}, indent=1, ensure_ascii=False))
    return 0 if out["result"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
