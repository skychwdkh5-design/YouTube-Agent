import hashlib, json, os, re, shutil, subprocess, sys, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ORCH = os.path.join(HERE, "orchestrate.py")
SRC = os.path.join(REPO, "productions", "neom-line")
HAVE_EVIDENCE = os.path.exists(os.path.join(SRC, "evidence", "stack", "provenance.json"))


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


class Base(unittest.TestCase):
    """Fixture: ONLY what an agent writes (notes.json, script.md, topic approval, visual reviews) plus reused real imagery.
    claims.json, episode.json, graphics_spec.json, the storyboard and everything else must be generated by the system."""

    @classmethod
    def setUpClass(cls):
        if not HAVE_EVIDENCE:
            raise unittest.SkipTest("EP005 evidence not present (run the orchestrator once with network)")

    def setUp(self):
        self.slug = f"_t_{os.getpid()}_{self._testMethodName[-14:]}"
        self.root = os.path.join(REPO, "productions", self.slug)
        os.makedirs(self.root)
        self.env = dict(os.environ)

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def agent_artifacts(self, notes=True, script=True, reviews=True, evidence=True, topic=True):
        if topic:
            shutil.copytree(os.path.join(SRC, "topic"), os.path.join(self.root, "topic"))
        if notes:
            shutil.copytree(os.path.join(SRC, "research"), os.path.join(self.root, "research"), ignore=shutil.ignore_patterns("report.md", "brief.json"))
        if script:
            shutil.copy(os.path.join(SRC, "script.md"), self.root)
        if reviews:
            os.makedirs(os.path.join(self.root, "qa"), exist_ok=True)
            shutil.copy(os.path.join(SRC, "qa", "visual_review.json"), os.path.join(self.root, "qa"))
        if evidence:
            shutil.copytree(os.path.join(SRC, "evidence"), os.path.join(self.root, "evidence"), copy_function=os.link)   # hardlinks: real imagery, no download

    def orch(self, *args, env=None):
        r = subprocess.run([sys.executable, ORCH, *args], capture_output=True, text=True, env=env or self.env, cwd=REPO, timeout=1200)
        try:
            return json.loads(r.stdout) if r.stdout.strip() else {}, r.returncode
        except ValueError:
            return {"raw": r.stdout, "err": r.stderr}, r.returncode

    def state(self):
        return json.load(open(os.path.join(self.root, "state.json")))

    def run_all(self, *extra, env=None):
        return self.orch("run", "--slug", self.slug, *extra, env=env)[0]

    def p(self, *a):
        return os.path.join(self.root, *a)

    def live_review(self):
        """Index of a review that matches a CURRENT frame (a review for a frame that no longer exists changes nothing)."""
        rep = json.load(open(self.p("qa", "visual_claims.json")))
        live = {(f["sha256"], tuple(sorted(i["claims"]))) for i in rep["items"] for f in i.get("frames", [])}
        rv = json.load(open(self.p("qa", "visual_review.json")))["reviews"]
        idx = [k for k, r in enumerate(rv) if (r["frame_sha256"], tuple(sorted(r["claims"]))) in live]
        self.assertTrue(idx, "fixture has no live review")
        return idx[0]


