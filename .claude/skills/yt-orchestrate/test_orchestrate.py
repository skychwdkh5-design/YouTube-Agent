class Pipeline(Base):
    def test_everything_is_generated_from_agent_artifacts_only(self):
        self.agent_artifacts()
        for g in GENERATED:
            self.assertFalse(os.path.exists(self.p(g)), g)                          # not handed to the system
        r = self.run_all()
        st = r["stages"]
        for s in ("topic", "research", "facts", "evidence", "script", "visualplan", "visuals", "storyboard", "visualcheck"):
            self.assertEqual(st[s], "done", (s, r))
        self.assertEqual((st["voice"], st["captions"], st["render"], st["qc"]), ("awaiting_approval", "waiting", "waiting", "waiting"))
        for g in GENERATED:
            self.assertTrue(os.path.exists(self.p(g)), g)                           # all produced by code
        self.assertEqual(json.load(open(self.p("episode.json")))["generated_by"], "yt-visual-planner")
        self.assertEqual(self.state()["costs"], [])                                 # nothing paid
        self.assertFalse(os.path.exists(self.p("voice", "narration.wav")))
        a = r["autonomy"]
        self.assertEqual(a["agent_needed_now"], 0)
        self.assertEqual(a["owner_gates_pending"], 2)
        self.assertGreaterEqual(a["fully_automated_done"], 6)
        self.assertIn("FULLY_AUTOMATED", open(self.p("release", "REVIEW.md")).read())
        self.assertIn("INCOMPLETE", open(self.p("release", "REVIEW.md")).read())

    def test_idempotent_rerun_and_state(self):
        self.agent_artifacts()
        self.run_all()
        before = {f: sha(self.p(f)) for f in ("claims.json", "episode.json", "timeline.json", "script.md", "qa/visual_claims.json")}
        attempts = {s: v["attempts"] for s, v in self.state()["stages"].items()}
        r2 = self.run_all()
        for s in ("topic", "research", "facts", "evidence", "script", "visualplan", "visuals", "storyboard", "visualcheck"):
            self.assertEqual(r2["stages"][s], "cached", s)
        self.assertEqual(before, {f: sha(self.p(f)) for f in before})
        now = {s: v["attempts"] for s, v in self.state()["stages"].items()}
        for s in attempts:
            if s not in ("voice", "release"):                                        # gates and the release summary are re-evaluated on purpose
                self.assertEqual(attempts[s], now[s], s)
        self.assertEqual(self.state()["schema"], "yt-orchestrate/1")

    def test_resume_after_hard_crash(self):
        self.agent_artifacts()
        env = dict(self.env, OA_CRASH_IN="storyboard")
        r = subprocess.run([sys.executable, ORCH, "run", "--slug", self.slug], capture_output=True, text=True, env=env, cwd=REPO, timeout=1200)
        self.assertEqual(r.returncode, 99)
        st = self.state()["stages"]
        self.assertEqual(st["storyboard"]["status"], "running")
        self.assertEqual(st["visuals"]["status"], "done")
        ev = st["evidence"]["attempts"]
        out = self.run_all()
        self.assertEqual(out["stages"]["storyboard"], "done")
        self.assertEqual(out["stages"]["evidence"], "cached")
        self.assertEqual(self.state()["stages"]["evidence"]["attempts"], ev)
        self.assertTrue(any("interrupted" in e.get("event", "") for e in self.state()["log"]))

    def test_changed_output_is_detected(self):
        self.agent_artifacts()
        self.run_all()
        g = self.p("graphics", "g_tiers.png")
        open(g, "ab").write(b"corrupt")
        out = self.run_all()
        self.assertEqual(out["stages"]["visuals"], "done")
        self.assertNotEqual(open(g, "rb").read()[-7:], b"corrupt")

    def test_edited_script_reruns_only_downstream(self):
        self.agent_artifacts()
        self.run_all()
        open(self.p("script.md"), "a").write("\nWe will keep watching.\n")
        out = self.run_all()
